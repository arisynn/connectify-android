export function resolveThemeDefinition(themeId?: string | null): ThemeDefinition {
  if (themeId && THEME_MAP[themeId]) {
    return THEME_MAP[themeId];
  }
  return THEME_MAP.sweets;
}

export function getThemeTilesForGame(gameId: GameId, themeId?: string | null): string[] {
  const theme = resolveThemeDefinition(themeId);
  if (gameId === 'match3') {
    return theme.match3TileIndices.map((idx) => theme.tileUrls[idx] ?? theme.tileUrls[0]);
  }
  return theme.tileUrls;
}
